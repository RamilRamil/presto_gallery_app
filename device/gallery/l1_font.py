# Cyrillic letters drawn exactly like a Latin one.
_SAME_AS_LATIN = {
    "А": "A", "В": "B", "Е": "E", "К": "K", "М": "M", "Н": "H",
    "О": "O", "Р": "P", "С": "C", "Т": "T", "Х": "X",
    "а": "a", "е": "e", "о": "o", "р": "p", "с": "c", "у": "y",
    "х": "x",
}


def glyph_rows(char):
    """Seven 5-bit rows for a character; unknown characters are drawn as '?'."""
    code = _GLYPHS.get(_SAME_AS_LATIN.get(char, char)) or _GLYPHS["?"]
    return [int(code[i:i + 2], 16) for i in range(0, 14, 2)]


def fit_text(text, max_chars):
    """Cut a name to max_chars, ending in an ellipsis when it was too long."""
    if len(text) <= max_chars:
        return text
    return text[:max(0, max_chars - 1)] + ELLIPSIS
